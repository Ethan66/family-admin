CREATE TABLE course (
    id BIGINT PRIMARY KEY AUTO_INCREMENT,
    family_id BIGINT NOT NULL,
    member_id BIGINT NOT NULL,
    member_name VARCHAR(100) NOT NULL,
    title VARCHAR(120) NOT NULL,
    course_date DATE NOT NULL,
    start_time TIME NOT NULL,
    end_time TIME NOT NULL,
    repeat_weekly TINYINT NOT NULL DEFAULT 0,
    color VARCHAR(12) NOT NULL,
    created_by BIGINT NOT NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by BIGINT NOT NULL,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    deleted TINYINT NOT NULL DEFAULT 0,
    INDEX idx_course_family_member_date (family_id, member_id, course_date, deleted),
    FOREIGN KEY (family_id) REFERENCES family(id),
    FOREIGN KEY (member_id) REFERENCES sys_user(id),
    CHECK (start_time < end_time)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE course_record (
    id BIGINT PRIMARY KEY AUTO_INCREMENT,
    family_id BIGINT NOT NULL,
    course_id BIGINT NOT NULL,
    member_id BIGINT NOT NULL,
    member_name VARCHAR(100) NOT NULL,
    title VARCHAR(120) NOT NULL,
    course_date DATE NOT NULL,
    start_time TIME NOT NULL,
    end_time TIME NOT NULL,
    status VARCHAR(12) NOT NULL,
    note VARCHAR(500) NOT NULL DEFAULT '',
    created_by BIGINT NOT NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by BIGINT NOT NULL,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    deleted TINYINT NOT NULL DEFAULT 0,
    UNIQUE KEY uk_course_record_date (course_id, course_date),
    INDEX idx_course_record_family_date (family_id, course_date, deleted),
    FOREIGN KEY (family_id) REFERENCES family(id),
    FOREIGN KEY (course_id) REFERENCES course(id),
    FOREIGN KEY (member_id) REFERENCES sys_user(id),
    CHECK (status IN ('ATTENDED', 'LEAVE'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
